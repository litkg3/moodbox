/** 用户从情绪小球进来时，把那股情绪作为背景交给模型，而不是当成一条用户消息 */
export function emotionContextLine(label: string | null): string | null {
  if (!label) return null;
  return `【背景】对方是从主页的「${label}」这颗情绪球走进来的，此刻多半正被这种感受占着。开场不要急着提问，先接住它。`;
}
